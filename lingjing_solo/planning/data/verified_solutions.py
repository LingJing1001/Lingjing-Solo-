# ─── 便捷查询 ─────────────────────────────────────────────
def get_solution(game: str, level: str) -> list | None:
    """根据游戏类型和关卡号返回预存动作序列。

    Args:
        game: "LS20" | "AR25" | "ARC" | "L7" | "L8" | "SU15" | "FT09"
        level: 关卡编号（字符串）

    Returns:
        动作 ID 列表（LS20/AR25/ARC/L7/L8），
        或坐标点击列表（SU15/FT09），或 None（未找到时）
    """
    if game == "LS20":
        return LS20_SOLUTIONS.get(level)
    if game == "AR25":
        return AR25_SOLUTIONS.get(level)
    if game == "ARC":
        return ARC_SOLUTIONS.get(level)
    if game == "L7":
        return L7_SOLUTION if level == "7" else None
    if game == "L8":
        return L8_SOLUTION["moves"] if level == "8" else None
    if game == "SU15":
        return SU15_SOLUTIONS.get(level)
    if game == "FT09":
        return FT09_SOLUTIONS.get(level)
    return None


