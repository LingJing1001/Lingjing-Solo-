def _to_actions(levels: dict[str, list[int]]) -> dict[str, list[str]]:
    return {k: [f"ACTION{n}" for n in seq] for k, seq in levels.items()}


def build_default_registry() -> PluginRegistry:
    reg = PluginRegistry()
    reg.register(
        CannedRoutePlugin(
            plugin_id="ls20_canned",
            game_ids=("ls20",),
            levels=_to_actions(_LS20),
        )
    )
    reg.register(
        CannedRoutePlugin(
            plugin_id="ar25_canned",
            game_ids=("ar25",),
            levels=_to_actions(_AR25),
        )
    )
    return reg


